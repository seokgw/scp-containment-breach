export function progressOf(solved) {
  const ids = new Set(
    solved.map((x) => (typeof x === "number" ? x : x.challenge_id)),
  );
  let clearance = 0;
  for (const chapter of chapters) {
    if (
      chapter.requiredClearance === clearance &&
      chapter.ids.every((id) => ids.has(id))
    )
      clearance++;
    else break;
  }
  return {
    solved: [...ids],
    score: challenges
      .filter((c) => ids.has(c.id))
      .reduce((sum, c) => sum + c.points, 0),
    clearance,
    completed: ids.size === 10,
  };
}
